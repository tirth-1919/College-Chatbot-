-- 1. Entity: extracted_facts
CREATE TABLE IF NOT EXISTS extracted_facts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    college_id UUID NOT NULL REFERENCES colleges(id) ON DELETE CASCADE,
    source_type VARCHAR(50) NOT NULL, -- 'WEBSITE', 'PDF', 'MANUAL'
    source_id UUID NOT NULL,
    category VARCHAR(100) NOT NULL, -- 'ADMISSION', 'FEES', 'COURSES', 'FACULTY', 'HOSTEL', 'SCHOLARSHIP'
    fact_key VARCHAR(255) NOT NULL,
    fact_value TEXT NOT NULL,
    verification_status VARCHAR(50) NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'APPROVED', 'REJECTED'
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE extracted_facts IS 'Atomic key-value claims (e.g. fees, deadlines) extracted from documents or web pages';

-- 2. Entity: knowledge_chunks (Embeddings & Semantic Vector Search Unit)
CREATE TABLE IF NOT EXISTS knowledge_chunks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    college_id UUID NOT NULL REFERENCES colleges(id) ON DELETE CASCADE,
    source_type VARCHAR(50) NOT NULL, -- 'OFFICIAL_WEBSITE', 'ADMIN_VERIFIED'
    source_id UUID NOT NULL,
    source_url TEXT,
    page_number INTEGER,
    chunk_text TEXT NOT NULL,
    embedding VECTOR(768), -- Google Gemini text-embedding-004 vector dimension (768)
    status knowledge_status NOT NULL DEFAULT 'PENDING_REVIEW',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE knowledge_chunks IS 'Text chunks and vector embeddings used by the RAG engine during student query retrieval';
COMMENT ON COLUMN knowledge_chunks.embedding IS '768-dimensional vector embedding generated by Google Gemini text-embedding-004';
COMMENT ON COLUMN knowledge_chunks.status IS 'Lifecycle state: PROCESSING, PENDING_REVIEW, APPROVED, PUBLISHED, REJECTED, STALE, SUPERSEDED, FAILED';

-- 3. Entity: knowledge_reviews
CREATE TABLE IF NOT EXISTS knowledge_reviews (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    chunk_id UUID NOT NULL REFERENCES knowledge_chunks(id) ON DELETE CASCADE,
    reviewed_by_user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    review_action VARCHAR(50) NOT NULL, -- 'APPROVE', 'REJECT', 'EDIT', 'PUBLISH', 'UNPUBLISH'
    notes TEXT,
    edited_chunk_text TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE knowledge_reviews IS 'Audit trail of administrative review actions (approvals, edits, rejections, publications)';

